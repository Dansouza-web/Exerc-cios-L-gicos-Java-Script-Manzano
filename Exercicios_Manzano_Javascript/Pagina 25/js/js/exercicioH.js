alert("Bem vindo ao calculo de volume de uma caixa");
const comprimento = Number(prompt("Digite o comprimento da sua caixa : "));
const largura = Number(prompt("Digite a largura da sua caixa : "));
const altura = Number(prompt("Digite a altura da sua caixa : "));
let volume = comprimento * largura * altura
alert(`o volume da caixa é de ${volume}`)