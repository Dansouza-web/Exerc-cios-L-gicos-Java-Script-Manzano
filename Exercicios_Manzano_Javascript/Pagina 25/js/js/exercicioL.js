alert("Bem vindo ao programa de soma dos quadrados");
const A = Number(prompt("Digite um valor para a variavel A : "));
const B = Number(prompt("Digite um valor para a variavel B : "));
const C = Number(prompt("Digite um valor para a variavel C: "));
somadosquadradosdostres = (A*A) + (B*B) + (C*C)
